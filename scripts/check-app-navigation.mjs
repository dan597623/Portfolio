import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3102/',{waitUntil:'networkidle'});
await page.evaluate(()=>window.navigationMarker='preserved');
await page.locator('header').getByRole('link',{name:"Let's Talk"}).click();
await page.waitForURL('**/contact');
if(await page.evaluate(()=>window.navigationMarker)!=='preserved')throw Error('Contact navigation reloaded document');
await page.locator('header').getByRole('button',{name:'About me',exact:true}).click();
await page.waitForURL('http://localhost:3102/');await page.waitForTimeout(900);
const top=await page.locator('#about-me').evaluate(e=>e.getBoundingClientRect().top);
if(top<0 || top>400)throw Error('Home section scroll failed: '+top);
await page.locator('header').getByRole('button',{name:'Projects',exact:true}).click();await page.waitForURL('**/projects');
await page.locator('a[href="/projects/my-tutor"]').first().click();await page.waitForURL('**/projects/my-tutor');
await page.waitForTimeout(400);
if(!await page.evaluate(()=>document.body.classList.contains('single-case_study')))throw Error('Case style missing');
await page.locator('header').getByRole('button',{name:'Dan, back to top'}).click();await page.waitForURL('http://localhost:3102/');await page.waitForTimeout(400);
await page.getByRole('button',{name:'Next testimonial',exact:true}).click();
if(!await page.locator('.project-testimonials__card.is-active').innerText().then(s=>s.includes("Dan's support")))throw Error('Carousel failed after navigation');
await page.getByRole('button',{name:'Switch color theme'}).click();
if(await page.evaluate(()=>document.documentElement.dataset.theme)!=='light')throw Error('Theme toggle failed after navigation');
console.log(JSON.stringify({softNavigation:true,sectionScroll:true,carousel:true,theme:true,errors}));
await browser.close();if(errors.length)process.exitCode=1;
